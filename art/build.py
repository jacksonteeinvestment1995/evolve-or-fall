#!/usr/bin/env python3
"""Merge art/src/*.spr into art/sprites.js and (if present) bake art/preview.src.html -> art/preview.html.
Python 3 stdlib only. Run from anywhere: python3 art/build.py"""
import os, sys, glob, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sprio
sprites, errs = {}, []
for f in sorted(glob.glob(os.path.join(HERE, 'src', '*.spr'))):
    d, e = sprio.parse_spr(f); errs += e
    for n, s in d.items():
        if n in sprites: errs.append(f'duplicate sprite {n} in {f}')
        s = dict(s); s.pop('_line', None); sprites[n] = s
for e in errs: print('parse error:', e)
order = {'hero': 0, 'villager': 1, 'hidden': 2, 'structure': 3, 'tile': 4, 'effect': 5, 'icon': 6}
out = {n: {'w': s['w'], 'h': s['h'], 'section': s['section'], 'label': s['label'], 'frames': s['frames']}
       for n, s in sorted(sprites.items(), key=lambda kv: kv[0])}
# keep manifest order (stable gallery order)
import validate
out = {n: out[n] for n in [k for k in validate.M if k in out] + [k for k in out if k not in validate.M]}
js = "/* Sprites: name -> {w, h, section, label, frames:[rows[]...]}. '.' = transparent. Generated by art/build.py from art/src/*.spr */\nconst SPRITES = {\n"
js += ',\n'.join(' ' + json.dumps(n) + ': {"w": %d, "h": %d, "section": %s, "label": %s, "frames": [\n%s\n ]}' % (
    s['w'], s['h'], json.dumps(s['section']), json.dumps(s['label'], ensure_ascii=False),
    ',\n'.join('  [\n' + ',\n'.join('   ' + json.dumps(r) for r in f) + '\n  ]' for f in s['frames'])) for n, s in out.items())
js += '\n};\n'
open(os.path.join(HERE, 'sprites.js'), 'w', encoding='utf-8').write(js)
print(f'wrote sprites.js: {len(out)} sprites')
tpl = os.path.join(HERE, 'preview.src.html')
if os.path.exists(tpl):
    t = open(tpl, encoding='utf-8').read()
    pal = open(os.path.join(HERE, 'palette.js'), encoding='utf-8').read()
    t = t.replace('/*@@PALETTE@@*/', pal).replace('/*@@SPRITES@@*/', js)
    open(os.path.join(HERE, 'preview.html'), 'w', encoding='utf-8').write(t)
    print('wrote preview.html', len(t), 'bytes')
sys.exit(1 if errs else 0)
